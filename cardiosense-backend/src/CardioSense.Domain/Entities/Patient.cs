// =============================================================================
// File           : Patient.cs
// Layer          : Domain / Entities
// Purpose        : Demographic and identity half of a patient's profile.
// Logic          : Age is derived from the date of birth; contact data can be updated, identity data cannot.
// Implementation : Sealed entity with private setters and a static factory; FileNumber is assigned by the
//                  database on insert.
// =============================================================================
using CardioSense.Domain.Common;
using CardioSense.Domain.Enums;

namespace CardioSense.Domain.Entities;

/// <summary>A monitored patient.</summary>
public sealed class Patient : Entity
{
    /// <summary>Maximum length of the full name.</summary>
    public const int NameMaxLength = 120;

    /// <summary>Maximum length of the phone number.</summary>
    public const int PhoneMaxLength = 20;

    /// <summary>Maximum length of the national id.</summary>
    public const int NationalIdMaxLength = 20;

    /// <summary>Used by EF Core.</summary>
    private Patient()
    {
    }

    /// <summary>Builds a patient after guarding every required value.</summary>
    private Patient(
        Guid userId, string fullName, DateOnly dateOfBirth, Gender gender, string nationalId, string phone,
        DateTimeOffset now)
        : base(now)
    {
        UserId = RequireId(userId, nameof(userId));
        FullName = RequireText(fullName, nameof(fullName), NameMaxLength);
        DateOfBirth = dateOfBirth;
        Gender = gender;
        NationalId = RequireText(nationalId, nameof(nationalId), NationalIdMaxLength);
        Phone = RequireText(phone, nameof(phone), PhoneMaxLength);
    }

    /// <summary>The login account (Users table) that owns this profile.</summary>
    public Guid UserId { get; private set; }

    /// <summary>Human-friendly sequential file number; generated by the database on insert.</summary>
    public int FileNumber { get; private set; }

    /// <summary>Full name.</summary>
    public string FullName { get; private set; } = null!;

    /// <summary>Date of birth.</summary>
    public DateOnly DateOfBirth { get; private set; }

    /// <summary>Gender.</summary>
    public Gender Gender { get; private set; }

    /// <summary>National id (14 digits in Egypt).</summary>
    public string NationalId { get; private set; } = null!;

    /// <summary>Contact phone (also used by the doctor's call button).</summary>
    public string Phone { get; private set; } = null!;

    /// <summary>Creates a new patient profile.</summary>
    public static Patient Create(
        Guid userId, string fullName, DateOnly dateOfBirth, Gender gender, string nationalId, string phone,
        DateTimeOffset now) =>
        new(userId, fullName, dateOfBirth, gender, nationalId, phone, now);

    /// <summary>Calculates the age in whole years on the given day.</summary>
    public int GetAge(DateOnly today)
    {
        var age = today.Year - DateOfBirth.Year;
        return DateOfBirth > today.AddYears(-age) ? age - 1 : age;
    }

    /// <summary>Approximates a date of birth when only an age is collected (birthday = today).</summary>
    public static DateOnly DateOfBirthFromAge(int ageYears, DateOnly today) => today.AddYears(-ageYears);

    /// <summary>Updates the editable contact fields; null means "leave unchanged".</summary>
    public void UpdateContact(string? fullName, string? phone)
    {
        if (fullName is not null)
        {
            FullName = RequireText(fullName, nameof(fullName), NameMaxLength);
        }

        if (phone is not null)
        {
            Phone = RequireText(phone, nameof(phone), PhoneMaxLength);
        }
    }
}
